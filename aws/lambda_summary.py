# Lambda : KhadsanDailySummary
# EventBridge เรียกทุกวัน 18:00 น. เวลาไทย (cron(0 11 * * ? *) = 11:00 UTC)
# อ่าน log ของวันนี้จาก S3 (logs/YYYY-MM-DD/*.json ที่เว็บเขียนไว้) แล้วส่งอีเมลสรุปผ่าน SNS
# ใช้แค่ boto3 ที่ Lambda มีให้อยู่แล้ว ไม่ต้องทำ Layer
#
# Environment variables ของ Lambda
#   S3_BUCKET       ชื่อ bucket ของตัวเอง เช่น khadsan-images-1660705185
#   SNS_TOPIC_ARN   ARN ของ topic khadsan-alerts
#
# วิธีใช้ : วางทั้งไฟล์ลงใน lambda_function.py ของ Lambda แล้วกด Deploy (Handler = lambda_function.lambda_handler)

import os
import json
from datetime import datetime, timezone, timedelta

import boto3

s3 = boto3.client("s3")
sns = boto3.client("sns")

BUCKET = os.environ["S3_BUCKET"]
TOPIC_ARN = os.environ["SNS_TOPIC_ARN"]
THAI_TZ = timezone(timedelta(hours=7))


def lambda_handler(event, context):
    # ทดสอบย้อนหลังได้ : Test event {"date": "2026-11-10"} / ปกติ {} = วันนี้ตามเวลาไทย
    day = (event or {}).get("date") or datetime.now(THAI_TZ).date().isoformat()
    totals = {"scans": 0, "total": 0, "fresh": 0, "rotten": 0, "recheck": 0}
    kinds = {}
    worst = None   # รูปที่คัดออกเยอะสุดของวัน

    pages = s3.get_paginator("list_objects_v2")
    for page in pages.paginate(Bucket=BUCKET, Prefix="logs/" + day + "/"):
        for obj in page.get("Contents", []):
            if not obj["Key"].endswith(".json"):
                continue
            body = s3.get_object(Bucket=BUCKET, Key=obj["Key"])["Body"].read()
            data = json.loads(body.decode("utf-8"))
            if str(data.get("created_at", ""))[:10] != day:
                continue
            totals["scans"] += 1
            for k in ("total", "fresh", "rotten", "recheck"):
                totals[k] += int(data.get(k, 0))
            for name, n in (data.get("kinds") or {}).items():
                kinds[name] = kinds.get(name, 0) + int(n)
            if worst is None or int(data.get("rotten", 0)) > int(worst.get("rotten", 0)):
                worst = data

    percent = round(totals["rotten"] * 100 / totals["total"]) if totals["total"] else 0
    lines = [
        "KhadSan AI สรุปผลประจำวัน " + day,
        "",
        "ตรวจทั้งหมด: " + str(totals["scans"]) + " ครั้ง / " + str(totals["total"]) + " ลูก",
        "สด: " + str(totals["fresh"]),
        "ให้ตรวจซ้ำ: " + str(totals["recheck"]),
        "คัดออก: " + str(totals["rotten"]) + " (" + str(percent) + "%)",
    ]
    if kinds:
        lines.append("ชนิด: " + ", ".join(k + " " + str(v) for k, v in sorted(kinds.items(), key=lambda kv: -kv[1])))
    if worst and int(worst.get("rotten", 0)) > 0:
        lines.append("รูปที่คัดออกเยอะสุด: " + str(worst.get("created_at", "")) + " คัดออก " + str(worst.get("rotten")) + " ลูก")
    if totals["scans"] == 0:
        lines.append("(วันนี้ยังไม่มีการตรวจ ค่า 0 เป็นเรื่องปกติ)")
    lines += ["", "Generated by AWS Lambda (KhadsanDailySummary)"]

    sns.publish(TopicArn=TOPIC_ARN,
                Subject="KhadSan AI Daily Summary - " + day,
                Message="\n".join(lines))
    return {"statusCode": 200, "body": {"date": day, "percent": percent, **totals}}
